const HEADER: &str = "% Generated by `cargo run --release --example paper_tables` in\n\
                      % libqueuingsim/. Do not edit by hand.\n";

fn pm(e: Estimate, d: usize) -> String {
    format!("${:.d$} \\pm {:.d$}$", e.mean, e.half_width)
}

/// A table cell that can compete for "best in its group": the value as
/// displayed (rounded to the printed precision) and its rendering.
struct Cell {
    value: f64,
    text: String,
}

fn cell(value: f64, d: usize, text: String) -> Cell {
    let s = 10f64.powi(d as i32);
    Cell {
        value: (value * s).round() / s,
        text,
    }
}

/// Bold the rendering of every cell whose displayed value is the best of
/// the group (all tied cells are bold). Math cells (`$...$`) get
/// `\mathbf`, text cells `\textbf`.
fn bold_best(cells: &mut [Cell], lower_is_better: bool) {
    let best = cells.iter().map(|c| c.value).fold(
        if lower_is_better {
            f64::INFINITY
        } else {
            f64::NEG_INFINITY
        },
        |a, b| {
            if lower_is_better { a.min(b) } else { a.max(b) }
        },
    );
    for c in cells.iter_mut().filter(|c| c.value == best) {
        c.text = if c.text.starts_with('$') && c.text.ends_with('$') {
            format!("$\\mathbf{{{}}}$", &c.text[1..c.text.len() - 1])
        } else {
            format!("\\textbf{{{}}}", c.text)
        };
    }
}

fn csv_line(fields: &[String]) -> String {
    fields.join(",")
}

/// Machine-readable copies of the table data, one per figure, written to
/// `data/` next to the tables. `scripts/plot_sim.py` reads them.
struct Data {
    files: Vec<(&'static str, String)>,
}

impl Data {
    fn push(&mut self, name: &'static str, header: &str, rows: &[String]) {
        let mut s = String::from(
            "# Generated by `cargo run --release --example paper_tables` in libqueuingsim/. \
             Synthetic workload; do not edit by hand.\n",
        );
        s.push_str(header);
        s.push('\n');
        for r in rows {
            s.push_str(r);
            s.push('\n');
        }
        self.files.push((name, s));
    }
}

fn table(caption: &str, label: &str, cols: &str, head: &str, rows: &[String]) -> String {
    table_sep(caption, label, cols, head, rows, "3pt")
}

/// `colsep` is the `\tabcolsep` of the tabular (`3pt` by default; `2pt`
/// for the wide tables that would otherwise exceed the column width).
fn table_sep(
    caption: &str,
    label: &str,
    cols: &str,
    head: &str,
    rows: &[String],
    colsep: &str,
) -> String {
    let mut s = String::from(HEADER);
    writeln!(s, "\\begin{{table}}[t]").unwrap();
    writeln!(s, "\\caption{{{caption}}}").unwrap();
    writeln!(s, "\\label{{{label}}}").unwrap();
    writeln!(
        s,
        "\\centering\\small\\setlength{{\\tabcolsep}}{{{colsep}}}"
    )
    .unwrap();
    writeln!(s, "\\begin{{tabular}}{{@{{}}{cols}@{{}}}}").unwrap();
    writeln!(s, "\\toprule\n{head} \\\\\n\\midrule").unwrap();
    for r in rows {
        writeln!(s, "{r} \\\\").unwrap();
    }
    writeln!(s, "\\bottomrule\n\\end{{tabular}}\n\\end{{table}}").unwrap();
    s
}

