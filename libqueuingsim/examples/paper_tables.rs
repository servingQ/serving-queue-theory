//! Generate the LaTeX tables and macros of the paper's simulation section.
//!
//! ```text
//! cargo run --release --example paper_tables            # writes ../paper/sim/
//! cargo run --release --example paper_tables -- <dir>   # writes <dir>
//! ```
//!
//! Every number in `paper/simulation.tex` comes from these files, so the
//! paper cannot drift from the code. Scenarios and seeds are the ones in
//! `src/validation.rs`; `scripts/check_sim.sh` regenerates the files and
//! fails if the committed copies differ.

use std::fmt::Write as _;
use std::path::PathBuf;

