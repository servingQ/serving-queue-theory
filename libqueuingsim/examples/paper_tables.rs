fn kingman() -> String {
    let s = Dist::HitMiss {
        p_hit: 0.96,
        hit: 0.05,
        miss: 5.0,
    };
    let rho = 0.7;
    let lam = rho / s.mean();
    let pk = pk_wait(lam, s.second_moment(), rho);
    let mut rows = vec![];
    for (i, ca2) in [2.0, 4.0, 8.0].into_iter().enumerate() {
        let ia = Dist::hyperexp_balanced(1.0 / lam, ca2);
        let cfg = QueueConfig {
            interarrival: ia.clone(),
            service: s.clone(),
            servers: 1,
            customers: 4_000_000,
            warmup: 200_000,
            seed: 70 + i as u64,
        };
        let w = queue::simulate(&cfg).wait;
        rows.push(format!(
            "{ca2:.0} & {pk:.2} & {} & {:.2}",
            pm(w, 2),
            kingman_bound(lam, ia.variance(), s.variance(), rho)
        ));
    }
    table(
        "Bursty (hyperexponential) arrivals with the service law of \
         Eq.~\\eqref{eq:cv2}, $\\rho=0.7$. $c_a^2$ is the interarrival \
         $\\mathrm{CV}^2$. Mean waits in seconds.",
        "tab:sim-kingman",
        "cccc",
        "$c_a^2$ & PK & Simulated $W_q$ & Kingman bound",
        &rows,
    )
}

fn offload() -> (String, usize, usize) {
    let mut rows = vec![];
    let (mut ok, mut total) = (0, 0);
    for bw in [5.0e3, 2.0e4, 1.0e5] {
        for n in [32, 64] {
            let run = |p| agentic::simulate(&offload_cfg(n, bw, p));
            let (nv, al, se, pr) = (
                run(OffloadPolicy::Never),
                run(OffloadPolicy::Always),
                run(OffloadPolicy::Selective),
                run(OffloadPolicy::Priced),
            );
            let mut async_cfg = offload_cfg(n, bw, OffloadPolicy::Always);
            async_cfg.fetch = FetchMode::Async;
            let al_async = agentic::simulate(&async_cfg);
            total += 1;
            if se.throughput >= 0.97 * nv.throughput.max(al.throughput) {
                ok += 1;
            }
            let mut pols: Vec<Cell> = [&nv, &al, &se, &pr]
                .iter()
                .map(|r| cell(r.throughput, 2, format!("{:.2}", r.throughput)))
                .collect();
            bold_best(&mut pols, false);
            rows.push(format!(
                "{:.0}k & {n} & {} & {} & {} & {} & {:.2} & {:.2} / {:.0}",
                bw / 1e3,
                pols[0].text,
                pols[1].text,
                pols[2].text,
                pols[3].text,
                al.stall_load,
                al_async.throughput,
                al_async.response.mean()
            ));
        }
    }
    let t = table(
        "Offloading with blocking fetches (the replica waits for the tier). \
         Throughput in turns/s by tier bandwidth (tokens/s), concurrency $N$ \
         and policy; the best of the four policies per row in bold. Priced: \
         selective with the price of a miss in place \
         of $\\Delta S(1+Q)$ (with blocking fetches both tests reduce to \
         transfer $<\\Delta S$). Stall: fraction of replica time spent waiting on \
         fetches under always-offload. Last column: always-offload when \
         fetches complete before the turn queues (asynchronous), as \
         throughput / mean turn response time in s (including the fetch).",
        "tab:sim-offload",
        "rrcccccc",
        "Tier & $N$ & Never & Always & Selective & Priced & Stall & Async",
        &rows,
    );
    (t, ok, total)
}

/// A cost ratio; ratios of 1000 or more in scientific notation.
fn ratio(x: f64, d: usize) -> String {
    if x < 1000.0 {
        format!("{x:.d$}")
    } else {
        let k = x.log10().floor();
        format!("${:.1}{{\\times}}10^{{{k:.0}}}$", x / 10f64.powf(k))
    }
}

/// A ratio for the CSV files: plain decimals, scientific past 10^4.
fn ratio_csv(x: f64) -> String {
    if x < 1.0e4 {
        format!("{x:.5}")
    } else {
        format!("{x:.4e}")
    }
}

type RatioOf = fn(&eviction::Ratios) -> f64;

const OFFLINE_POLICIES: [(&str, RatioOf); 3] = [
    ("SF", |r| r.shortest_first),
    ("Density", |r| r.density_first),
    ("Guarded", |r| r.guarded_density),
];

fn evict_offline(data: &mut Data) -> String {
    let mut rows = vec![];
    let mut sweeps = vec![];
    for (name, id, rm, seed) in [
        ("equal $p_i$", "equal_p", ResumeModel::Uniform, 5),
        (
            "$p_i\\sim U[0.05,1]$",
            "varied_p",
            ResumeModel::Varied { lo: 0.05 },
            99,
        ),
        (
            "$p_i$ falls with $c_i$",
            "p_falls_with_c",
            ResumeModel::ShorterResumes,
            7,
        ),
    ] {
        sweeps.push((name, id, eviction::sweep(3000, 12, 200, rm, seed)));
    }
    sweeps.push((
        "arbitrary $w_i$",
        "arbitrary_w",
        eviction::sweep_weighted(3000, 12, 200, 161),
    ));
    let mut summary = vec![];
    let mut samples = vec![];
    for (name, id, v) in sweeps {
        let mut means = vec![];
        let mut maxes = vec![];
        for (pol, f) in OFFLINE_POLICIES {
            let mean = v.iter().map(f).sum::<f64>() / v.len() as f64;
            let max = v.iter().map(f).fold(0.0, f64::max);
            // Compete on the value at the printed precision; ratios in
            // scientific notation never win, so their raw value is fine.
            means.push(cell(mean, 3, ratio(mean, 3)));
            maxes.push(cell(max, 2, ratio(max, 2)));
            summary.push(csv_line(&[
                id.to_string(),
                pol.to_string(),
                ratio_csv(mean),
                ratio_csv(max),
            ]));
        }
        bold_best(&mut means, true);
        bold_best(&mut maxes, true);
        let cells: Vec<String> = means
            .iter()
            .zip(&maxes)
            .map(|(m, x)| format!("{} / {}", m.text, x.text))
            .collect();
        rows.push(format!("{name} & {}", cells.join(" & ")));
        for (i, r) in v.iter().enumerate() {
            samples.push(csv_line(&[
                id.to_string(),
                i.to_string(),
                ratio_csv(r.shortest_first),
                ratio_csv(r.density_first),
                ratio_csv(r.guarded_density),
            ]));
        }
    }
    data.push(
        "evict-offline.csv",
        "regime,policy,mean_cost_over_opt,max_cost_over_opt",
        &summary,
    );
    data.push(
        "evict-offline-samples.csv",
        "regime,instance,sf,density,guarded",
        &samples,
    );
    table(
        "Offline eviction: cost relative to the exact optimum of \
         \\eqref{eq:evict-priced}, mean / max over 3000 random instances per row \
         (12 programs, $c_i\\in\\{1,\\dots,200\\}$, $\\Delta C$ a random \
         10--60\\,\\% of the total); the lowest mean and the lowest max per \
         row in bold. First three rows: costs $p_ic_i^2$. \
         Last row: weights $w_i$ log-uniform on $[10^{-4},10^5]$, independent \
         of $c_i$. Guarded: the guarded density greedy of \
         Prop.~\\ref{prop:guarded}.",
        "tab:sim-evict",
        "lccc",
        "Costs & SF & Density & Guarded",
        &rows,
    )
}

