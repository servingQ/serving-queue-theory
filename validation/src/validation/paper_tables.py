def macros(all_checks, open_rows, trace_rows, price_rows, offload_ok, offload_cells) -> str:
    passed = sum(1 for c in all_checks if c.passed)
    pd_check = next(c for c in all_checks if c.id == "pd_win_condition_decisions")
    agree, total = pd_check.observed.split()[0].split("/")
    m = [HEADER.rstrip("\n")]

    def cmd(name, value):
        m.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    cmd("simChecks", len(all_checks))
    cmd("simCalA", fixed(CAL_PREFILL_LINEAR * 1e3, 3))
    cmd("simCalB", fixed(CAL_PREFILL_QUADRATIC * 1e9, 2))
    cmd("simCalOmega", fixed(CAL_DECODE_STEP, 3))
    cmd("simChecksPassed", passed)
    pct = 0.0
    for d in (0.01, 0.05):
        r = seq_price.price_scenario(d)
        pct = fmax(pct, 100.0 * abs(r.dl_d.mean) / r.l_d.mean)
    cmd("simDecodeShiftPct", fixed(pct, 1))

    def at(rate, pol, end):
        return next(
            r
            for r in open_rows
            if r.cap == OPEN_CAP and r.rate == rate and r.policy == pol and r.end_known == end
        )

    ratios = []
    for rate in seq_open.RATES:
        best = _fmin(at(rate, p, True).ttft.mean for p in seq_open.POLICIES if p != E.Lru)
        ratios.append(at(rate, E.Lru, True).ttft.mean / best)
    cmd("simEvictLruRatioMin", fixed(_fmin(ratios), 1))
    cmd("simEvictLruRatioMax", fixed(_fmax(ratios), 1))
    r0 = seq_open.RATES[0]
    known, unknown = at(r0, E.PricedMemory, True), at(r0, E.PricedMemory, False)
    cmd("simEndUnknownHit", fixed(unknown.hit_rate.mean, 2))
    cmd("simEndKnownHit", fixed(known.hit_rate.mean, 2))
    cmd("simEndUnknownTtftRatio", fixed(unknown.ttft.mean / known.ttft.mean, 1))
    cmd("simPdAgree", agree)
    cmd("simPdCells", total)
    cmd("simOffloadOk", offload_ok)
    cmd("simOffloadCells", offload_cells)
    corpus = workload.weka()
    ratio_ = [r.pk_wait.mean / r.wait.mean for r in trace_rows]
    tight = [
        r for r in trace_rows
        if math.isfinite(r.kv) and r.cap == seq_replay.trace_cap(corpus, r.kv, TRACE_CAP_FACTORS[0])
    ]  # fmt: skip
    loose = [
        r for r in trace_rows
        if math.isfinite(r.kv) and r.cap == seq_replay.trace_cap(corpus, r.kv, TRACE_CAP_FACTORS[1])
    ]  # fmt: skip
    open_ = [r for r in trace_rows if not math.isfinite(r.kv)]
    cmd("simTracePkRatioMin", fixed(_fmin(ratio_), 0))
    cmd("simTracePkRatioMax", fixed(_fmax(ratio_), 0))
    cmd("simTraceOpenCvMin", fixed(_fmin(r.cv2.mean for r in open_), 0))
    cmd("simTraceOpenCvMax", fixed(_fmax(r.cv2.mean for r in open_), 0))
    cmd("simTraceOpenTtftMin", fixed(_fmin(r.ttft.mean for r in open_), 0))
    cmd("simTraceOpenTtftMax", fixed(_fmax(r.ttft.mean for r in open_), 0))
    cmd("simTraceTightHitMin", fixed(_fmin(r.hit_rate.mean for r in tight), 2))
    cmd("simTraceTightReusedMin", fixed(_fmin(r.reused.mean for r in tight), 2))
    cmd("simTraceTightMixMin", fixed(100.0 * _fmin(r.mixture_share.mean for r in tight), 0))
    cmd("simTraceTightMixMax", fixed(100.0 * _fmax(r.mixture_share.mean for r in tight), 0))
    cmd("simTraceLooseHitMax", fixed(_fmax(r.hit_rate.mean for r in loose), 2))
    cmd("simTraceLooseTtftMin", fixed(_fmin(r.ttft.mean for r in loose), 0))
    cmd("simTraceSessions", len(corpus.sessions))
    cmd("simTraceEntryMaxHours", fixed(_fmax(r.entry_wait.mean / 3600.0 for r in trace_rows), 0))
    small = [r.dl_p.mean / r.lo for r in price_rows if r.delta <= 0.03]
    large = [r.dl_p.mean / r.lo for r in price_rows if r.delta > 0.03]
    cmd("simPriceSmallRatioMin", fixed(_fmin(small), 2))
    cmd("simPriceSmallRatioMax", fixed(_fmax(small), 2))
    cmd("simPriceLargeRatioMin", fixed(_fmin(large), 1))
    cmd("simPriceLargeRatioMax", fixed(_fmax(large), 1))
    cmd("simPriceLiveMin", fixed(_fmin(r.live for r in price_rows), 0))
    cmd("simPriceLiveMax", fixed(_fmax(r.live for r in price_rows), 0))
    fin_ratio = [r.dl_p.mean / r.finite for r in price_rows]
    cmd("simPriceFiniteRatioMin", fixed(_fmin(fin_ratio), 0))
    cmd("simPriceFiniteRatioMax", fixed(_fmax(fin_ratio), 0))
    over = [r.lo / r.dl_p.mean for r in price_rows]
    cmd("simPriceOverMin", fixed(_fmin(over), 0))
    cmd("simPriceOverMax", fixed(_fmax(over), 0))
    cap_ok = all(r.dl_p.mean <= r.live1 - r.l_p for r in price_rows)
    cmd("simPriceCapHolds", "every" if cap_ok else "not every")
    fin = checks.finite_source_scenario()
    cmd("simFiniteRatioMax", fixed(fin[0].wait_open / fin[0].wait_exact, 1))
    cmd("simFiniteRatioMin", fixed(fin[-1].wait_open / fin[-1].wait_exact, 2))
    cmd("simFiniteNMin", fin[0].n)
    cmd("simFiniteNMax", fin[-1].n)
    cmd("simFiniteRho", disp(checks.FINITE_SOURCE_RHO))
    return "\n".join(m) + "\n"


