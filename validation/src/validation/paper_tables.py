def evict_offline(data: Data) -> str:
    sweeps = []
    for name, id_, rm, seed in [
        ("equal $p_i$", "equal_p", eviction.UNIFORM, 5),
        ("$p_i\\sim U[0.05,1]$", "varied_p", eviction.varied(0.05), 99),
        ("$p_i$ falls with $c_i$", "p_falls_with_c", eviction.SHORTER_RESUMES, 7),
    ]:
        sweeps.append((name, id_, eviction.sweep(3000, 12, 200, rm, seed)))
    sweeps.append(("arbitrary $w_i$", "arbitrary_w", eviction.sweep_weighted(3000, 12, 200, 161)))
    rows, summary, samples = [], [], []
    for name, id_, v in sweeps:
        means, maxes = [], []
        for pol, f in OFFLINE_POLICIES:
            vals = [f(r) for r in v]
            mean = ssum(vals) / len(v)
            mx = fold_max(vals, 0.0)
            means.append(cell(mean, 3, ratio(mean, 3)))
            maxes.append(cell(mx, 2, ratio(mx, 2)))
            summary.append(csv_line([id_, pol, ratio_csv(mean), ratio_csv(mx)]))
        bold_best(means, True)
        bold_best(maxes, True)
        cells = [f"{m.text} / {x.text}" for m, x in zip(means, maxes, strict=True)]
        rows.append(f"{name} & {' & '.join(cells)}")
        for i, r in enumerate(v):
            samples.append(
                csv_line(
                    [
                        id_,
                        str(i),
                        ratio_csv(r.shortest_first),
                        ratio_csv(r.density_first),
                        ratio_csv(r.guarded_density),
                    ]
                )
            )
    data.push("evict-offline.csv", "regime,policy,mean_cost_over_opt,max_cost_over_opt", summary)
    data.push("evict-offline-samples.csv", "regime,instance,sf,density,guarded", samples)
    return table(
        "Offline eviction: cost relative to the exact optimum of "
        "\\eqref{eq:evict-priced}, mean / max over 3000 random instances per row "
        "(12 programs, $c_i\\in\\{1,\\dots,200\\}$, $\\Delta C$ a random "
        "10--60\\,\\% of the total); the lowest mean and the lowest max per "
        "row in bold. First three rows: costs $p_ic_i^2$. "
        "Last row: weights $w_i$ log-uniform on $[10^{-4},10^5]$, independent "
        "of $c_i$; shortest-first does not see $w_i$ there, and its ratio is "
        "the price of ignoring the weights. Guarded: the guarded density greedy "
        "of \\S\\ref{sec:evict}.",
        "tab:sim-evict",
        "lccc",
        "Costs & SF & Density & Guarded",
        rows,
    )


