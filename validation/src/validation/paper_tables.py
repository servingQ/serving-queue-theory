def open_csv_line(r: OpenEvictRow) -> str:
    f = [fixed(r.rate, 2), str(r.cap), open_policy_id(r)]
    for e in (r.throughput, r.hit_rate, r.ttft, r.ttft_p99, r.response, r.entry_wait):
        f += [fixed(e.mean, 4), fixed(e.half_width, 4)]
    f += [str(r.collapsed), str(OPEN_SEEDS)]
    return csv_line(f)


def open_group_rows(group: list[OpenEvictRow], render) -> list[str]:
    """Rows of one (Λ, cap) group with the best value per metric in bold:
    X (max), hit (max), TTFT (min, with and without its half-width), p99 (min)."""

    def col(f, d, with_hw):
        return [cell(f(r).mean, d, pm(f(r), d) if with_hw else fixed(f(r).mean, d)) for r in group]

    x = col(lambda r: r.throughput, 2, False)
    hit = col(lambda r: r.hit_rate, 2, False)
    ttft_pm = col(lambda r: r.ttft, 2, True)
    ttft = col(lambda r: r.ttft, 2, False)
    p99 = col(lambda r: r.ttft_p99, 1, False)
    bold_best(x, False)
    bold_best(hit, False)
    bold_best(ttft_pm, True)
    bold_best(ttft, True)
    bold_best(p99, True)
    return [
        render(r, [x[i].text, hit[i].text, ttft_pm[i].text, ttft[i].text, p99[i].text])
        for i, r in enumerate(group)
    ]


