def pm(e: Estimate, d: int) -> str:
    return f"${fixed(e.mean, d)} \\pm {fixed(e.half_width, d)}$"


@dataclass
class Cell:
    """A table cell that can compete for "best in its group": the value as
    displayed (rounded to the printed precision) and its rendering."""

    value: float
    text: str


def cell(value: float, d: int, text: str) -> Cell:
    s = 10.0**d
    return Cell(rround(value * s) / s, text)


def bold_best(cells: list[Cell], lower_is_better: bool) -> None:
    """Bold every cell whose displayed value is the best of the group."""
    best = math.inf if lower_is_better else -math.inf
    for c in cells:
        best = fmin(best, c.value) if lower_is_better else fmax(best, c.value)
    for c in cells:
        if c.value == best:
            if c.text.startswith("$") and c.text.endswith("$"):
                c.text = f"$\\mathbf{{{c.text[1:-1]}}}$"
            else:
                c.text = f"\\textbf{{{c.text}}}"


def csv_line(fields) -> str:
    return ",".join(fields)


class Data:
    """Machine-readable copies of the table data, one per figure."""

    def __init__(self):
        self.files: list[tuple[str, str]] = []

    def push(self, name: str, header: str, rows: list[str]) -> None:
        self.files.append((name, DATA_HEADER + header + "\n" + "".join(r + "\n" for r in rows)))


def table(caption, label, cols, head, rows, colsep="3pt", size="small") -> str:
    s = HEADER
    s += "\\begin{table}[htbp]\n"
    s += f"\\caption{{{caption}}}\n"
    s += f"\\label{{{label}}}\n"
    s += f"\\centering\\{size}\\setlength{{\\tabcolsep}}{{{colsep}}}\n"
    s += f"\\begin{{tabular}}{{@{{}}{cols}@{{}}}}\n"
    s += f"\\toprule\n{head} \\\\\n\\midrule\n"
    for r in rows:
        s += f"{r} \\\\\n"
    s += "\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    return s


