def kingman() -> str:
    s = HitMiss(0.96, 0.05, 5.0)
    rho = 0.7
    lam = rho / s.mean()
    pk = pk_wait(lam, s.second_moment(), rho)
    rows = []
    for i, ca2 in enumerate([2.0, 4.0, 8.0]):
        ia = hyperexp_balanced(1.0 / lam, ca2)
        w = queue.simulate(QueueConfig(ia, s, 1, 4_000_000, 200_000, 70 + i)).wait
        rows.append(
            f"{fixed(ca2, 0)} & {fixed(pk, 2)} & {pm(w, 2)} & {fixed(kingman_bound(lam, ia.variance(), s.variance(), rho), 2)}"
        )
    return table(
        "Bursty (hyperexponential) arrivals with the service law of "
        "\\S\\ref{sec:congestion}, $\\rho=0.7$. $c_a^2$ is the interarrival "
        "$\\mathrm{CV}^2$. Mean waits in seconds.",
        "tab:sim-kingman",
        "cccc",
        "$c_a^2$ & PK & Simulated $W_q$ & Kingman bound",
        rows,
    )


def offload() -> tuple[str, int, int]:
    rows, ok, total = [], 0, 0
    for bw in (5.0e3, 2.0e4, 1.0e5):
        for n in (32, 64):

            def run(p, n=n, bw=bw):
                return agentic.simulate(checks.offload_cfg(n, bw, p))

            nv, al, se, pr = (
                run(OffloadPolicy.Never),
                run(OffloadPolicy.Always),
                run(OffloadPolicy.Selective),
                run(OffloadPolicy.Priced),
            )
            async_cfg = checks.offload_cfg(n, bw, OffloadPolicy.Always)
            async_cfg.fetch = FetchMode.Async
            al_async = agentic.simulate(async_cfg)
            total += 1
            if se.throughput >= 0.97 * fmax(nv.throughput, al.throughput):
                ok += 1
            pols = [cell(r.throughput, 2, fixed(r.throughput, 2)) for r in (nv, al, se, pr)]
            bold_best(pols, False)
            rows.append(
                f"{fixed(bw / 1e3, 0)}k & {n} & {pols[0].text} & {pols[1].text} & {pols[2].text} & "
                f"{pols[3].text} & {fixed(al.stall_load, 2)} & {fixed(al_async.throughput, 2)} / "
                f"{fixed(al_async.response.mean(), 0)}"
            )
    t = table(
        "Offloading with blocking fetches (the replica waits for the tier). "
        "Throughput in turns/s by tier bandwidth (tokens/s), concurrency $N$ "
        "and policy; the best of the four policies per row in bold. Priced: "
        "selective with the price of a miss in place "
        "of $\\Delta S(1+Q)$ (with blocking fetches both tests reduce to "
        "transfer $<\\Delta S$). Stall: fraction of replica time spent waiting on "
        "fetches under always-offload. Last column: always-offload when "
        "fetches complete before the turn queues (asynchronous), as "
        "throughput / mean turn response time in s (including the fetch).",
        "tab:sim-offload",
        "rrcccccc",
        "Tier & $N$ & Never & Always & Selective & Priced & Stall & Async",
        rows,
    )
    return t, ok, total


def ratio(x: float, d: int) -> str:
    """A cost ratio; ratios of 1000 or more in scientific notation."""
    if x < 1000.0:
        return fixed(x, d)
    k = math.floor(math.log10(x))
    return f"${fixed(x / 10.0**k, 1)}{{\\times}}10^{{{fixed(k, 0)}}}$"


def ratio_csv(x: float) -> str:
    """A ratio for the CSV files: plain decimals, scientific past 10^4."""
    return fixed(x, 5) if x < 1.0e4 else sci_fixed(x, 4)


